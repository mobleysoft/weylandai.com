#!/usr/bin/env node
// g068, reworked by g074: the public SightX sheet view shows only a set we authored.
//
//   node tools/accuracy/g068/build-sheets.mjs
//
// The harvested sets are third-party architects' drawings kept as local review copies (tools/corpus/harvest
// README: no republication), so none of them is built into the public bundle; review of harvested sets stays
// on the Mac. The one public set is the WeylandAI Building (tools/bidset/make.mjs, SAMPLE PROJECT - NOT A REAL
// BUILDING), set 4847b09e633103f7, with its g066 placement record (tools/corpus/harvest/placement/<sha16>.json).
// Its PDF is written to weyland-sightx-worker/assets/building/<sha16>.pdf.bin (Wrangler's Data rule, the subx
// worker's client-ocr precedent) and drawn in the visitor's browser by the self-hosted pdf.js; the record goes
// to src/data/sheets/records.js and the PDF import to src/data/sheets/pdfs.js. Served at
// /api/sightx/sheets/<sha16> and /api/sightx/sheets/<sha16>/set.pdf, opened by /sightx/?set=<sha16>.
import fs from "node:fs";
import path from "node:path";
import crypto from "node:crypto";
import { fileURLToPath } from "node:url";

const HERE = path.dirname(fileURLToPath(import.meta.url));
const REPO = path.join(HERE, "../../..");
const PLACEMENT = path.join(REPO, "tools/corpus/harvest/placement");
const WORKER = path.join(REPO, "weyland-sightx-worker");
const ASSETS = path.join(WORKER, "assets/building");
const DATA = path.join(WORKER, "src/data/sheets");
// Sets we authored, and only those: sha16 -> the PDF in this repository.
export const OWN_SETS = { "4847b09e633103f7": "tools/bidset/out/weylandai-building-bidset.pdf" };

// The card's fields: what the plan reader placed and what reader A read on the schedule row. Nothing added.
const TAG_FIELDS = ["mark", "sheet", "page", "x", "y", "h", "room", "room_name", "room_by", "unsure", "matched_by", "also_on", "note", "shared_mark",
  "location", "size", "width_inches", "height_inches", "pair", "door_type", "frame_type", "material", "fire_rating", "hardware_group", "door_pages"];
const ROW_FIELDS = ["page", "mark", "location", "size", "door_type", "frame_type", "material", "fire_rating", "hardware_group"];
const pick = (o, keys) => Object.fromEntries(keys.filter((k) => o[k] !== undefined).map((k) => [k, o[k]]));
const round2 = (v) => (typeof v === "number" ? Math.round(v * 100) / 100 : v);

export function sheetRecord(rec) {
  const tags = rec.tags.map((t) => ({ ...pick(t, TAG_FIELDS), x: round2(t.x), y: round2(t.y), h: round2(t.h), schedule_rows: (t.schedule_rows || []).map((r) => pick(r, ROW_FIELDS)) }));
  const sheets = rec.sheets.map((s) => ({ page: s.page, sheet: s.sheet, title: s.title, width: s.width, height: s.height, scales: s.scales, points_per_foot: s.points_per_foot }));
  return { set: { ...rec.set, pdf: "/api/sightx/sheets/" + rec.set.sha16 + "/set.pdf" }, sheets, tags, summary: { marks_total: rec.summary.marks_total, marks_placed: rec.summary.marks_placed, placed_rate: rec.summary.placed_rate, sheets_total: rec.summary.sheets_total, unplaced: rec.summary.unplaced || [] } };
}

function main(argv) {
  const asked = argv.filter((a) => /^[0-9a-f]{16}$/.test(a));
  for (const sha of asked) if (!OWN_SETS[sha]) throw new Error(sha + " is not a set we authored: harvested sets are local review copies and are not published (g074)");
  const list = asked.length ? asked : Object.keys(OWN_SETS);
  fs.rmSync(ASSETS, { recursive: true, force: true });
  fs.mkdirSync(ASSETS, { recursive: true });
  fs.mkdirSync(DATA, { recursive: true });
  const records = {}, pdfs = [];
  for (const sha of list) {
    const pdf = path.join(REPO, OWN_SETS[sha]);
    const bytes = fs.readFileSync(pdf);
    const digest = crypto.createHash("sha256").update(bytes).digest("hex");
    if (digest.slice(0, 16) !== sha) throw new Error(pdf + " is not set " + sha + " (sha256 " + digest + ")");
    records[sha] = sheetRecord(JSON.parse(fs.readFileSync(path.join(PLACEMENT, sha + ".json"), "utf8")));
    fs.writeFileSync(path.join(ASSETS, sha + ".pdf.bin"), bytes);
    pdfs.push({ sha, file: sha + ".pdf.bin", bytes: bytes.length });
  }
  fs.writeFileSync(path.join(DATA, "records.js"), "// Generated by tools/accuracy/g068/build-sheets.mjs: do not edit by hand.\n// The placement records of sets we authored, opened on their plan sheets at /sightx/?set=<sha16>. No harvested set (g074).\nexport const SHEET_SETS = " + JSON.stringify(records) + ";\n");
  fs.writeFileSync(path.join(DATA, "pdfs.js"), "// Generated by tools/accuracy/g068/build-sheets.mjs: do not edit by hand.\n// The PDFs of sets we authored (Wrangler Data modules), drawn in the browser by the self-hosted pdf.js.\n" +
    pdfs.map((p, i) => "import p" + i + " from \"../../../assets/building/" + p.file + "\";").join("\n") + "\nexport const SHEET_PDFS = {\n" + pdfs.map((p, i) => "  " + JSON.stringify(p.sha) + ": p" + i + ",").join("\n") + "\n};\n");
  fs.writeFileSync(path.join(HERE, "sheets-summary.json"), JSON.stringify({ sets: list.map((sha) => ({ sha16: sha, pdf: OWN_SETS[sha], bytes: pdfs.find((p) => p.sha === sha).bytes, placed: records[sha].summary.marks_placed + " of " + records[sha].summary.marks_total, sheets: records[sha].sheets.map((s) => s.sheet + " p." + s.page) })) }, null, 2) + "\n");
  console.log(JSON.stringify(list.map((sha) => ({ sha, placed: records[sha].summary.marks_placed + "/" + records[sha].summary.marks_total, sheets: records[sha].sheets.map((s) => s.sheet) }))));
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) main(process.argv.slice(2));
